"""Merge the frozen strict main table with the two new baselines.

Output: results/fgbench/p0_baselines/main_table_v2.{csv,tex}
The frozen original (results/fgbench/strict_main_table.csv) is never modified.

Run:  python fgbench/experiments/p0_baselines/make_main_table.py
"""
from __future__ import annotations

from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parents[3]
CACHE = ROOT / "results" / "fgbench"
OUT = CACHE / "p0_baselines"
FACETS = [("COCO", "Entity"), ("COCO", "Quantity"), ("VG", "Attribute"),
          ("VG", "Action"), ("VG", "Relation")]
ORDER = ["cos", "csls", "gmm", "lemon", "traced", "centered", "abtt", "crd"]


def main() -> int:
    old = pd.read_csv(CACHE / "strict_main_table.csv", encoding="utf-8-sig")
    new = pd.read_csv(OUT / "baselines_raw.csv", encoding="utf-8-sig")
    # ABTT rows carry the selected k in the method name (abtt_k4 etc.)
    new["method"] = new.method.str.replace(r"^abtt_k\d+$", "abtt", regex=True)
    new = new[new.auroc.notna() & new.method.isin(["centered", "abtt"])]

    rows = []
    for ds, facet in FACETS:
        o = old[(old.dataset == ds) & (old.facet == facet)]
        for m in ORDER:
            if m in ("centered", "abtt"):
                r = new[(new.facet == facet) & (new.method == m)].iloc[0]
                rows.append({"dataset": ds, "facet": facet, "method": m,
                             "auroc": round(float(r.auroc), 4),
                             "auprc": round(float(r.auprc), 4),
                             "auroc_seedmean": None, "auroc_seedsd": None,
                             "k": int(r.k), "n_test": int(r.n_test),
                             "source": "p0_baselines/run_baselines.py"})
            else:
                s = o[o.method == m]
                if s.empty:
                    continue
                s = s.iloc[0]
                # CRD: report the three-seed mean when available (paper convention)
                auc = (float(s.auroc_seedmean) if pd.notna(s.auroc_seedmean)
                       else float(s.auroc))
                rows.append({"dataset": ds, "facet": facet, "method": m,
                             "auroc": auc, "auprc": float(s.auprc),
                             "auroc_seedmean": s.auroc_seedmean,
                             "auroc_seedsd": s.auroc_seedsd, "k": None,
                             "n_test": None,
                             "source": "strict_main_table.csv"})
    df = pd.DataFrame(rows)
    df.to_csv(OUT / "main_table_v2.csv", index=False, encoding="utf-8-sig")

    # LaTeX (booktabs, IEEE-friendly)
    name = {"cos": "CLIP cosine", "csls": "CLIP + CSLS", "gmm": "GMM-based",
            "lemon": "LEMoN-style", "traced": "TRACED-style",
            "centered": "Mean-centred cosine", "abtt": "ABTT cosine",
            "crd": "\\textbf{CRD (ours)}"}
    cols = ["Entity", "Quantity", "Attribute", "Action$^\\dagger$", "Relation"]
    best = {f: df[df.facet == f].auroc.max() for f in
            ["Entity", "Quantity", "Attribute", "Action", "Relation"]}
    lines = []
    for m in ORDER:
        cells = []
        for f in ["Entity", "Quantity", "Attribute", "Action", "Relation"]:
            r = df[(df.facet == f) & (df.method == m)]
            if r.empty:
                cells.append("---")
                continue
            r = r.iloc[0]
            v = f"{r.auroc:.4f}"
            if abs(r.auroc - best[f]) < 1e-9:
                v = f"\\textbf{{{v}}}"
            if m == "crd" and pd.notna(r.auroc_seedsd):
                # value on line 1, +-SD in scriptsize on line 2
                v = ("\\shortstack{" + v + "\\\\\\scriptsize$\\pm$"
                     + f"{r.auroc_seedsd:.4f}" + "}")
            cells.append(v)
        lines.append(f"{name[m]:26s} & " + " & ".join(cells) + r" \\")
    body = "\n".join(lines)
    tex = f"""% auto-generated by fgbench/experiments/p0_baselines/make_main_table.py
\\begin{{table*}}[t]
\\centering
\\small
\\setlength{{\\tabcolsep}}{{9pt}}
\\caption{{AUROC on the shared FGBench v1-strict test split, frozen CLIP ViT-B/16
for every row. CRD reports mean $\\pm$ standard deviation over three seeds and is
scored as the mean of the three calibrated score vectors; the two feature-debiasing
baselines use no labels and no gradient training. $^\\dagger$Action selects
$\\lambda$ on an internal validation split.}}
\\label{{tab:main}}
\\begin{{tabular}}{{lccccc}}
\\toprule
Method & {' & '.join(cols)} \\\\
\\midrule
{body}
\\bottomrule
\\end{{tabular}}
\\end{{table*}}
"""
    (OUT / "main_table_v2.tex").write_text(tex, encoding="utf-8")
    print(df.pivot(index="method", columns="facet", values="auroc").to_string())
    print("\nwrote", OUT / "main_table_v2.csv", "and .tex")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
