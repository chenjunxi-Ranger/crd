"""LEMoN-style mislabelled-caption benchmark, then CLIP cosine vs CRD on it.

Why this exists: LEMoN (Zhang et al., arXiv:2407.18941) does not ship a dataset;
it builds one on the fly from COCO / Flickr30k with a caption-swap protocol. This
script re-implements that protocol on the local COCO val2014 annotations so CRD
can be tested on a benchmark whose noise is generated by someone else's rule.

Protocol (copied from lib/datasets/noise_captioning.py, same variable names):

    build_index(nouns)              noun -> rows containing it
    calc_noise_by_integer_matching  pick int(frac*N) rows with >=1 noun,
                                    replace each by another row sharing a noun
    noise_given_dict                swap the sentence, label = (new != gold)

Differences, stated explicitly: we use one caption per (image, annotation) row of
COCO val2014 and split 70/15/15 by image id; LEMoN uses the Karpathy split over
the full 2014 corpus. The generator rule itself is unchanged.

Run:  python fgbench/experiments/lemon_protocol/run_lemon_protocol.py [--frac 0.2]
"""
from __future__ import annotations

import argparse
import json
import sys
import time
from pathlib import Path

import numpy as np
import pandas as pd
from sklearn.metrics import average_precision_score, roc_auc_score

ROOT = Path(__file__).resolve().parents[3]
sys.path.insert(0, str(ROOT))
sys.path.insert(0, str(ROOT / "fgbench" / "audit"))

import os

from fgbench.common import COCO_ANN  # noqa: E402

COCO_IMG = Path(os.environ.get("CRD_COCO_IMG", COCO_ANN.parent / "val2014"))

OUT = ROOT / "results" / "fgbench" / "lemon_protocol"
OUT.mkdir(parents=True, exist_ok=True)
N_IMAGES = 5000
SEED_SPLIT = 0
SEED_NOISE = 42                     # LEMoN default


# --------------------------------------------------------------- noise rule
def build_index(arr):
    max_val = max([max(s) for s in arr if len(s) > 0]) + 1
    sets = [set(a) for a in arr]
    return {i: [c for c, s in enumerate(sets) if i in s] for i in range(max_val)}


def calc_noise_by_integer_matching(cat_labels, frac_noise=0.3, seed=42):
    index = build_index(cat_labels)
    rng = np.random.default_rng(seed)
    cand = [i for i in np.arange(len(cat_labels)) if len(cat_labels[i]) > 0]
    to_change = rng.choice(cand, int(frac_noise * len(cat_labels)), replace=False)
    change = {}
    for i in to_change:
        obj = rng.choice(cat_labels[i])
        subset = np.setdiff1d(index[obj], [i])
        if len(subset) > 0:
            change[i] = int(rng.choice(subset, 1)[0])
    return change


def noise_given_dict(meta, d):
    meta_c = meta.copy()
    meta_c["gold_sentence"] = meta_c["sentence"]
    src = meta.index[list(d.keys())]
    dst = meta.index[list(d.values())]
    meta_c.loc[src, "sentence"] = meta.loc[dst, "sentence"].values
    meta_c["is_mislabel"] = (meta_c["sentence"] != meta_c["gold_sentence"])
    return meta_c


# ------------------------------------------------------------------- build
def build(frac: float) -> pd.DataFrame:
    cache = OUT / f"rows_frac{frac:.2f}.parquet"
    if cache.is_file():
        print(f"cache hit {cache.name}", flush=True)
        return pd.read_parquet(cache)

    import spacy
    nlp = spacy.load("en_core_web_sm", disable=["ner", "parser"])
    ann = json.loads((COCO_ANN / "captions_val2014.json").read_text(encoding="utf-8"))
    fname = {im["id"]: im["file_name"] for im in ann["images"]}
    rows = [{"image_id": a["image_id"], "sentence": a["caption"].strip()}
            for a in ann["annotations"] if a["image_id"] in fname]
    d = pd.DataFrame(rows).drop_duplicates()
    imgs = np.array(sorted(d.image_id.unique()))[:N_IMAGES]
    d = d[d.image_id.isin(imgs)].reset_index(drop=True)
    print(f"{len(d)} captions over {d.image_id.nunique()} images", flush=True)

    # nouns -> integer ids (vocabulary over the whole split, as LEMoN does)
    vocab, nouns = {}, []
    for doc in nlp.pipe(d.sentence.tolist(), batch_size=512):
        ids = []
        for t in doc:
            if t.pos_ in ("NOUN", "PROPN") and len(t.lemma_) > 2 and not t.is_stop:
                w = t.lemma_.lower()
                if w not in vocab:
                    vocab[w] = len(vocab)
                ids.append(vocab[w])
        nouns.append(sorted(set(ids)))
    d["nouns_int"] = nouns

    # split by image id so no image crosses splits
    rng = np.random.default_rng(SEED_SPLIT)
    ids = d.image_id.unique().copy()
    rng.shuffle(ids)
    n = len(ids)
    part = {"train": ids[: int(0.70 * n)],
            "val": ids[int(0.70 * n): int(0.85 * n)],
            "test": ids[int(0.85 * n):]}

    out = []
    for split, chosen in part.items():
        sub = d[d.image_id.isin(chosen)].reset_index(drop=True)
        sub["sentence_gold"] = sub.sentence
        nd = calc_noise_by_integer_matching(sub.nouns_int.values, frac, SEED_NOISE)
        sub = noise_given_dict(sub, nd).reset_index(drop=True)
        sub["split"] = split
        sub["path"] = sub.image_id.map(lambda i: str(COCO_IMG / fname[i]))
        out.append(sub)
        print(f"  {split:5s} rows {len(sub):6d}  images {sub.image_id.nunique():5d}  "
              f"mislabel {sub.is_mislabel.mean():.3f}", flush=True)

    full = pd.concat(out, ignore_index=True)
    full = full.rename(columns={"sentence": "caption", "is_mislabel": "label"})
    full[["split", "image_id", "path", "caption", "sentence_gold", "label"]]\
        .to_parquet(cache, index=False)
    print(f"wrote {cache.name}", flush=True)
    return full


# ---------------------------------------------------------------- features
def features(d: pd.DataFrame) -> dict:
    """Incrementally cached: different noise fractions swap in different captions."""
    cache = OUT / "features.npz"
    img, txt = {}, {}
    if cache.is_file():
        z = np.load(cache, allow_pickle=True)
        img = {k: v for k, v in zip(z["img_ids"].astype(str), z["img_vec"])}
        txt = {k: v for k, v in zip(z["txt_keys"], z["txt_vec"])}
        print(f"  cache: {len(img)} images, {len(txt)} captions", flush=True)

    need_i = [i for i in d.image_id.unique() if str(i) not in img]
    need_t = [c for c in d.caption.unique() if c not in txt]
    if not need_i and not need_t:
        return {"img": img, "txt": txt}

    from fgbench.models.crd_backbone import ClipBB
    bb = ClipBB()
    t0 = time.time()
    if need_i:
        paths = [d[d.image_id == i].path.iat[0] for i in need_i]
        U = bb.images(paths)
        img.update({str(k): v for k, v in zip(need_i, U)})
        print(f"  encoded {len(need_i)} images in {time.time()-t0:.0f}s", flush=True)
    if need_t:
        V = bb.texts(need_t)
        txt.update(dict(zip(need_t, V)))
        print(f"  encoded {len(need_t)} captions in {time.time()-t0:.0f}s", flush=True)

    np.savez_compressed(cache,
                        img_ids=np.array(list(img.keys())),
                        img_vec=np.stack(list(img.values())),
                        txt_keys=np.array(list(txt.keys())),
                        txt_vec=np.stack(list(txt.values())))
    return {"img": img, "txt": txt}


# ------------------------------------------------------------------ eval
def auc(y, x):
    return float(roc_auc_score(y, -x))


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--frac", type=float, default=0.2)
    ap.add_argument("--steps", type=int, default=1500)
    ap.add_argument("--seeds", default="0,1,2")
    a = ap.parse_args()

    d = build(a.frac)
    f = features(d)
    U = np.stack([f["img"][str(i)] for i in d.image_id])
    V = np.stack([f["txt"][c] for c in d.caption])
    S = np.einsum("ij,ij->i", U, V)

    masks = {s: (d.split == s).to_numpy() for s in ("train", "val", "test")}
    y_va, y_te = d.label[masks["val"]].to_numpy(), d.label[masks["test"]].to_numpy()
    mu, sd = float(S[masks["train"]].mean()), float(S[masks["train"]].std() + 1e-8)
    Z = (S - mu) / sd

    from fgbench.models.crd_backbone import Off
    import torch
    rows = []
    for seed in (int(x) for x in a.seeds.split(",")):
        torch.manual_seed(seed)
        head = Off(d=U.shape[1]).to("cuda" if torch.cuda.is_available() else "cpu")
        dev = next(head.parameters()).device
        opt = torch.optim.AdamW(head.parameters(), lr=1e-3, weight_decay=1e-4)
        Ut = torch.tensor(U[masks["train"]], device=dev)
        Vt = torch.tensor(V[masks["train"]], device=dev)
        Mt = torch.tensor(Z[masks["train"]], device=dev, dtype=torch.float32)
        rng = np.random.default_rng(seed)
        for _ in range(a.steps):
            idx = torch.tensor(rng.integers(0, len(Ut), 256), device=dev)
            loss = torch.nn.functional.huber_loss(head(Ut[idx], Vt[idx]), Mt[idx])
            opt.zero_grad(); loss.backward(); opt.step()
        with torch.no_grad():
            mh_va = head(torch.tensor(U[masks["val"]], device=dev),
                         torch.tensor(V[masks["val"]], device=dev)).cpu().numpy()
            mh_te = head(torch.tensor(U[masks["test"]], device=dev),
                         torch.tensor(V[masks["test"]], device=dev)).cpu().numpy()
        lam = max(np.round(np.arange(0, 2.01, 0.1), 1),
                  key=lambda L: auc(y_va, Z[masks["val"]] - L * mh_va))
        raw, crd = Z[masks["test"]], Z[masks["test"]] - lam * mh_te
        rows.append({"seed": seed, "lam": float(lam),
                     "auroc_cos": round(auc(y_te, raw), 4),
                     "auroc_crd": round(auc(y_te, crd), 4),
                     "auprc_cos": round(float(average_precision_score(y_te, -raw)), 4),
                     "auprc_crd": round(float(average_precision_score(y_te, -crd)), 4),
                     "delta_pp": round((auc(y_te, crd) - auc(y_te, raw)) * 100, 2)})
        print(rows[-1], flush=True)
        np.savez_compressed(OUT / f"scores_frac{a.frac:.2f}_s{seed}.npz",
                            image_id=d.image_id[masks["test"]].values, y=y_te,
                            cos=raw, crd=crd, lam=np.array([lam]))

    r = pd.DataFrame(rows)
    r.to_csv(OUT / f"result_frac{a.frac:.2f}.csv", index=False, encoding="utf-8-sig")
    print(f"\nmean  cos {r.auroc_cos.mean():.4f}  crd {r.auroc_crd.mean():.4f}  "
          f"Δ {r.delta_pp.mean():+.2f}pp  (sd {r.auroc_crd.std(ddof=1):.4f})")
    print("wrote", OUT)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
